-- ---------------------------------------------------------------------
-- 2) 확인 — 관리자 계정 하나만 남으면 정상입니다
-- ---------------------------------------------------------------------
select
  coalesce(u.email, p.email)                         as "이메일",
  case when u.id is null then '없음' else '있음' end as "로그인계정",
  case when p.id is null then '없음' else '있음' end as "회원정보",
  coalesce(p.name, '-')                              as "이름",
  coalesce(p.role, '-')                              as "권한"
from auth.users u
full outer join public.profiles p on p.id = u.id;
